"""Snapshot of the moon API for the static mini demos of the landing page (demo/data/snapshot.js).

Usage: python tools/snapshot.py http://localhost:8000 demo/data/snapshot.js  (run from apps/landing/pitch)
The server must let a caller with no session read (AUTH_REQUIRED=false, the default).

Both mini demos read it: the dashboard (demo/) and the crew app (demo-app/).
"""
import json
import sys
import urllib.request
from datetime import date, timedelta

API, OUT = sys.argv[1], sys.argv[2]
TODAY = date(2021, 11, 2)
FROM = TODAY - timedelta(days=365)


def get(path):
    return json.load(urllib.request.urlopen(API + path))


crew = get("/api/crew")["crew"]
data = {
    "today": TODAY.isoformat(),
    "crew": crew,
    # The names on the sign-in screen of the crew app. Never a PIN: the mini demo takes any PIN
    "users": get("/api/auth/users"),
    # Not read from the server: its link settings belong to the machine that takes the snapshot.
    # The mini demo is a moon server with no link to Earth.
    "node": {"role": "moon", "sync_configured": False, "earth_url": None, "pending_push_rows": None, "last_push": None, "last_pull": None},
    "panels": {},
    "details": {},
    "checklists": {},
    # Hydration and breathing of the demo date: the goal of each crew member; the visitor logs the rest
    "hydration": {},
    "breathing": {},
}
for member in crew:
    panel = get(f"/api/crew/{member['id']}/panel?date={TODAY}")
    data["panels"][member["id"]] = panel
    data["checklists"][member["id"]] = get(f"/api/crew/{member['id']}/tasks/{TODAY}")
    data["hydration"][member["id"]] = get(f"/api/crew/{member['id']}/hydration/{TODAY}")
    data["breathing"][member["id"]] = get(f"/api/crew/{member['id']}/breathing/{TODAY}")
    for indicator in panel["indicators"]:
        data["details"][f"{member['id']}/{indicator['id']}"] = get(
            f"/api/crew/{member['id']}/indicators/{indicator['id']}?from={FROM}&to={TODAY}"
        )

text = (
    f"// Generated by tools/snapshot.py from the moon API, for {TODAY.isoformat()}. Real data, read only.\n"
    "window.DEMO_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
)
with open(OUT, "w", encoding="utf-8", newline="\n") as file:
    file.write(text)
print(len(crew), "crew", len(data["details"]), "details", len(text) // 1024, "KB")
