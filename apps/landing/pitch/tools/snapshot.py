"""Snapshot of the moon API for the static mini demo of the landing page (demo/data/snapshot.js).

Usage: python tools/snapshot.py http://localhost:8000 demo/data/snapshot.js  (run from apps/landing/pitch)
The server must let a caller with no session read (AUTH_REQUIRED=false, the default).
"""
import json, sys, urllib.request
from datetime import date, timedelta
API, OUT = sys.argv[1], sys.argv[2]
TODAY = date(2021, 11, 2)
FROM = TODAY - timedelta(days=365)
get = lambda p: json.load(urllib.request.urlopen(API + p))
crew = get("/api/crew")["crew"]
data = {"today": TODAY.isoformat(), "crew": crew, "panels": {}, "details": {}}
for m in crew:
    panel = get(f"/api/crew/{m['id']}/panel?date={TODAY}")
    data["panels"][m["id"]] = panel
    for ind in panel["indicators"]:
        d = get(f"/api/crew/{m['id']}/indicators/{ind['id']}?from={FROM}&to={TODAY}")
        data["details"][f"{m['id']}/{ind['id']}"] = d
text = "// Generated by the snapshot of the moon API on " + TODAY.isoformat() + ". Real data, read only.\nwindow.DEMO_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(OUT, "w", encoding="utf-8", newline="\n").write(text)
print(len(crew), "crew", len(data["details"]), "details", len(text) // 1024, "KB")
