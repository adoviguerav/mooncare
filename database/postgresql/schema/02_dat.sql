-- Data tables. Same model as docs/mvp_architecture.md, section 2.

CREATE TABLE dat.crew_member (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE dat.reading (
  crew_member_id INTEGER          NOT NULL REFERENCES dat.crew_member (id),
  indicator_id   TEXT             NOT NULL REFERENCES cfg.indicator (id),
  taken_at       TIMESTAMP        NOT NULL,   -- no time zone, as decided in the MVP architecture
  value          DOUBLE PRECISION NOT NULL,
  PRIMARY KEY (crew_member_id, indicator_id, taken_at)
);
-- The primary key already serves the two queries of the API:
-- latest reading per indicator up to a date, and the history between two dates.
