-- Accounts and sign-in. Both servers have this same structure. See services/api/app/auth.py.
--
-- Users are managed on earth and downloaded by the moon with the configuration (pull), so the crew can sign in
-- with no link. Sessions and sign-in events belong to the server where they happen and are never synchronised.

-- Who can sign in. A crew user is linked to their crew member; an earth administrator is not a crew member.
-- Which server each role signs in on: crew_member, medical_officer and commander on the moon, earth_admin on earth.
CREATE TABLE dat.app_user (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name   TEXT    NOT NULL,
  role           TEXT    NOT NULL CHECK (role IN ('crew_member', 'medical_officer', 'commander', 'earth_admin')),
  crew_member_id INTEGER UNIQUE REFERENCES dat.crew_member (id),
  pin_hash       TEXT    NOT NULL,            -- argon2. Never the PIN itself
  is_active      BOOLEAN NOT NULL DEFAULT true,
  sync_seq       BIGINT  NOT NULL DEFAULT nextval('his.sync_seq'),
  -- Crew roles belong to a crew member; the earth administrator does not
  CHECK ((role = 'earth_admin') = (crew_member_id IS NULL))
);

CREATE TRIGGER bump_sync_seq BEFORE UPDATE ON dat.app_user FOR EACH ROW EXECUTE FUNCTION his.bump_sync_seq();

-- One row per signed-in device. The token itself is never stored, only its SHA-256.
CREATE TABLE dat.session (
  token_hash   TEXT        PRIMARY KEY,
  user_id      INTEGER     NOT NULL REFERENCES dat.app_user (id),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at   TIMESTAMPTZ NOT NULL,          -- 10 days after sign-in
  revoked_at   TIMESTAMPTZ                    -- set on sign-out
);

CREATE INDEX session_user_id_idx ON dat.session (user_id);

-- Every sign-in attempt and sign-out. Append only. Also used to lock an account after repeated wrong PINs.
CREATE TABLE his.auth_event (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     REFERENCES dat.app_user (id),
  event       TEXT        NOT NULL CHECK (event IN ('login_ok', 'login_failed', 'login_locked', 'logout')),
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX auth_event_user_idx ON his.auth_event (user_id, occurred_at DESC);
