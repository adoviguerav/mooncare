-- Configuration tables. Same model as docs/mvp_architecture.md, section 2.

CREATE TABLE cfg.source (
  id       TEXT PRIMARY KEY,   -- readable key, e.g. 'lifesnaps'
  name     TEXT NOT NULL,
  url      TEXT NOT NULL,
  citation TEXT NOT NULL
);

CREATE TABLE cfg.indicator (
  id             TEXT PRIMARY KEY,   -- readable key, e.g. 'glucose'
  name           TEXT NOT NULL,
  unit           TEXT,               -- NULL for the mood indicators
  how_to_measure TEXT NOT NULL,      -- the brief asks for it per measurement
  why_it_matters TEXT NOT NULL,      -- the short explanation for R4
  source_id      TEXT NOT NULL REFERENCES cfg.source (id),
  display_order  INTEGER NOT NULL UNIQUE   -- order of the panel. SQLite used rowid; PostgreSQL has none
);

CREATE TABLE cfg.rule (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  indicator_id     TEXT NOT NULL REFERENCES cfg.indicator (id),
  low              DOUBLE PRECISION,
  high             DOUBLE PRECISION,
  title            TEXT NOT NULL,
  explanation      TEXT NOT NULL,
  action           TEXT NOT NULL,
  threshold_source TEXT NOT NULL,    -- where the limit comes from (R11). Never a limit without it
  CHECK (low IS NOT NULL OR high IS NOT NULL),
  CHECK (low IS NULL OR high IS NULL OR low <= high)
);

CREATE INDEX rule_indicator_id_idx ON cfg.rule (indicator_id);
