def get_draw_date(sample_label: str) -> date:
    match = SAMPLE_LABEL_PATTERN.fullmatch(sample_label)
    if match is None:
        raise ValueError(f"Unknown sample label {sample_label!r}")
    reference, days = match.group(1), timedelta(days=int(match.group(2)))
    return LAUNCH_DATE - days if reference == "L" else LANDING_DATE + days


def read_glucose_readings(metabolic_panel_csv: Path, inspiration4_code: str) -> list[Reading]:
    readings = []
    with metabolic_panel_csv.open(newline="", encoding="utf-8-sig") as csv_file:
        for row in csv.DictReader(csv_file):
            crew_code, _, sample_label = row["Sample Name"].split("_")
            if crew_code != inspiration4_code or row[GLUCOSE_COLUMN] == "":
                continue
            taken_at = f"{get_draw_date(sample_label).isoformat()}T00:00"
            readings.append(Reading("glucose", taken_at, float(row[GLUCOSE_COLUMN])))
    return readings


def read_heart_rate_readings(hourly_csv: Path, lifesnaps_id: str, offset_days: int) -> list[Reading]:
    readings = []
    with hourly_csv.open(newline="", encoding="utf-8-sig") as csv_file:
        for row in csv.DictReader(csv_file):
            if row["id"] != lifesnaps_id or row["bpm"] == "":
                continue
            day = datetime.fromisoformat(row["date"]).date() + timedelta(days=offset_days)
            taken_at = f"{day.isoformat()}T{int(float(row['hour'])):02d}:00"
            readings.append(Reading("heart_rate", taken_at, float(row["bpm"])))
    return readings


def read_daily_readings(daily_csv: Path, lifesnaps_id: str, offset_days: int) -> list[Reading]:
    readings = []
    with daily_csv.open(newline="", encoding="utf-8-sig") as csv_file:
        for row in csv.DictReader(csv_file):
            if row["id"] != lifesnaps_id:
                continue
            day = datetime.fromisoformat(row["date"]).date() + timedelta(days=offset_days)
            taken_at = f"{day.isoformat()}T00:00"
            for indicator_id, column in DAILY_COLUMNS.items():
                cell = row.get(column)  # None when a short row leaves the column out: the same as an empty cell
                if cell not in (None, ""):
                    readings.append(Reading(indicator_id, taken_at, float(cell)))
    return readings


def build_mood_day_counts(readings: list[Reading]) -> list[Reading]:
    """For each day with a mood entry, on how many of the 14 days ending on it the mood was chosen.

    A day with no entry counts as not chosen.
    """
    counts = []
    for mood_id, count_id in MOOD_DAY_COUNT_IDS.items():
        value_by_day = {
            date.fromisoformat(reading.taken_at[:10]): reading.value
            for reading in readings
            if reading.indicator_id == mood_id
        }
        for day in sorted(value_by_day):
            window_start = day - timedelta(days=MOOD_WINDOW_DAYS - 1)
            chosen_days = sum(
                value for other_day, value in value_by_day.items() if window_start <= other_day <= day
            )
            counts.append(Reading(count_id, f"{day.isoformat()}T00:00", float(chosen_days)))
    return counts


def read_crew_readings(pairing: CrewPairing, dataset_files: DatasetFiles) -> list[Reading]:
    daily_readings = read_daily_readings(
        dataset_files.lifesnaps_daily, pairing.lifesnaps_id, pairing.lifesnaps_offset_days
    )
    return (
        (read_glucose_readings(dataset_files.metabolic_panel, pairing.inspiration4_code) if pairing.inspiration4_code else [])
        + read_heart_rate_readings(dataset_files.lifesnaps_hourly, pairing.lifesnaps_id, pairing.lifesnaps_offset_days)
        + daily_readings
        + build_mood_day_counts(daily_readings)
    )


# --- From rows to SQL ---

SqlValue = str | int | float | None


def to_sql_literal(value: SqlValue) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        raise TypeError("Booleans are not used in the seeds")
    if isinstance(value, int | float):
        return repr(value)
    return "'" + value.replace("'", "''") + "'"


def build_inserts(table: str, columns: Sequence[str], rows: Iterable[Sequence[SqlValue]]) -> str:
    """One INSERT per ROWS_PER_INSERT rows, so a big table stays a few large statements."""
    statements = []
    batch: list[str] = []
    column_list = ", ".join(columns)

    def flush() -> None:
        if batch:
            statements.append(f"INSERT INTO {table} ({column_list}) VALUES\n" + ",\n".join(batch) + ";\n")
            batch.clear()

    for row in rows:
        batch.append("  (" + ", ".join(to_sql_literal(value) for value in row) + ")")
        if len(batch) == ROWS_PER_INSERT:
            flush()
    flush()
    return "".join(statements)


def reset_identity(table: str) -> str:
    """The seeds insert explicit ids, so the identity sequence must continue after the highest one."""
    return f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), (SELECT max(id) FROM {table}));\n"


def with_header(body: str) -> str:
    # No BEGIN or COMMIT here: whoever loads the files decides the transaction, so a failed load leaves nothing
    return GENERATED_HEADER + "\n" + body


def build_sources_sql() -> str:
    rows = [(source.id, source.name, source.url, source.citation) for source in SOURCES]
    return with_header(build_inserts("cfg.source", ("id", "name", "url", "citation"), rows))


def build_indicators_sql() -> str:
    columns = ("id", "name", "unit", "how_to_measure", "why_it_matters", "source_id", "display_order")
    # The panel lists the indicators in the order INDICATORS defines them
    rows = [
        (i.id, i.name, i.unit, i.how_to_measure, i.why_it_matters, i.source_id, position)
        for position, i in enumerate(INDICATORS, start=1)
    ]
    return with_header(build_inserts("cfg.indicator", columns, rows))


def build_rules_sql() -> str:
    # Ids follow the order of RULES, as SQLite numbered them, so the ids in the contracts do not change
    columns = ("id", "indicator_id", "low", "high", "title", "explanation", "action", "threshold_source")
    rows = [
        (position, r.indicator_id, r.low, r.high, r.title, r.explanation, r.action, r.threshold_source)
        for position, r in enumerate(RULES, start=1)
    ]
    return with_header(build_inserts("cfg.rule", columns, rows) + reset_identity("cfg.rule"))


def build_crew_sql(crew: list[CrewPairing]) -> str:
    rows = [(position, pairing.name, pairing.role) for position, pairing in enumerate(crew, start=1)]
    return with_header(build_inserts("dat.crew_member", ("id", "name", "role"), rows) + reset_identity("dat.crew_member"))


def build_readings_sql(crew: list[CrewPairing], dataset_files: DatasetFiles) -> str:
    rows: list[tuple[int, str, str, float]] = []
    for crew_member_id, pairing in enumerate(crew, start=1):
        readings = read_crew_readings(pairing, dataset_files)
        rows.extend((crew_member_id, reading.indicator_id, reading.taken_at, reading.value) for reading in readings)
        log.info("%s: %d readings", pairing.name, len(readings))
    rows.sort()
    return with_header(build_inserts("dat.reading", ("crew_member_id", "indicator_id", "taken_at", "value"), rows))


@dataclass(frozen=True)
class StationDose:
    day: str
    instrument: str
    module: str
    mean_rate_ugy_h: float
    absorbed_dose_ugy: float
    hours_measured: int


def read_station_doses(radlab_dir: Path) -> list[StationDose]:
    """One dose per instrument and day from RadLab's readings (a few per hour, absorbed dose rate in µGy/h).

    The day's dose is its mean rate times 24 hours. A day needs readings in at least 12 of its hours: with fewer,
    the mean could miss the passages through the South Atlantic Anomaly that carry much of the dose.
    """
    rates: dict[tuple[str, str, str], list[float]] = {}
    hours: dict[tuple[str, str, str], set[str]] = {}
    for tsv in sorted(radlab_dir.glob("*.tsv")):
        with tsv.open(newline="", encoding="utf-8") as tsv_file:
            for row in csv.DictReader(tsv_file, delimiter="\t"):
                if row.get("absorbed_dose_rate") in (None, ""):
                    continue
                key = (row["timestamp"][:10], row["instrument"], row["module"])
                rates.setdefault(key, []).append(float(row["absorbed_dose_rate"]))
                hours.setdefault(key, set()).add(row["timestamp"][11:13])
    doses = []
    for (day, instrument, module), values in sorted(rates.items()):
        measured = len(hours[(day, instrument, module)])
        if measured < 12:
            continue
        mean = sum(values) / len(values)
        doses.append(StationDose(day, instrument, module, round(mean, 4), round(mean * 24, 2), measured))
    return doses


def build_station_dose_sql(radlab_dir: Path | None) -> str:
    doses = read_station_doses(radlab_dir) if radlab_dir else []
    log.info("Station radiation: %d instrument-days", len(doses))
    columns = ("day", "instrument", "module", "mean_rate_ugy_h", "absorbed_dose_ugy", "hours_measured")
    rows = [(d.day, d.instrument, d.module, d.mean_rate_ugy_h, d.absorbed_dose_ugy, d.hours_measured) for d in doses]
    return with_header(build_inserts("dat.station_dose", columns, rows) if rows else "-- No RadLab files given\n")


def build_daily_tasks_sql() -> str:
    columns = ("id", "title", "xp", "completion", "display_order")
    rows = [(t.id, t.title, t.xp, t.completion, position) for position, t in enumerate(DAILY_TASKS, start=1)]
    return with_header(build_inserts("cfg.daily_task", columns, rows))


def build_seed_files(crew: list[CrewPairing], dataset_files: DatasetFiles) -> dict[str, str]:
    """File name to content, in the order they must be loaded."""
    builders: dict[str, Callable[[], str]] = {
        "10_cfg_sources.sql": build_sources_sql,
        "11_cfg_indicators.sql": build_indicators_sql,
        "12_cfg_rules.sql": build_rules_sql,
        "13_cfg_daily_tasks.sql": build_daily_tasks_sql,
        "20_dat_crew.sql": lambda: build_crew_sql(crew),
        "21_dat_readings.sql": lambda: build_readings_sql(crew, dataset_files),
        "22_dat_station_dose.sql": lambda: build_station_dose_sql(dataset_files.radlab_dir),
    }
    return {file_name: build() for file_name, build in builders.items()}


def write_seed_files(seeds_dir: Path, seed_files: dict[str, str]) -> None:
    seeds_dir.mkdir(parents=True, exist_ok=True)
    for file_name, content in seed_files.items():
        (seeds_dir / file_name).write_text(content, encoding="utf-8", newline="\n")
        log.info("Wrote %s", file_name)


